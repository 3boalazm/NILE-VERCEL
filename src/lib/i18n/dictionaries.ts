/**
 * `Dictionary["products"]["resultsCount"]` is the one function-valued
 * field anywhere in the dictionary (a pluralization helper) — Next.js
 * refuses to serialize a function across a Server->Client component
 * boundary, so any component that might be rendered from inside a Client
 * Component (e.g. the wishlist page, which needs browser-only
 * localStorage state) needs this narrower shape instead of the full
 * `Dictionary`. A real `Dictionary` object already satisfies this type
 * structurally, so existing Server Component callers pass one in
 * unchanged.
 */
export type ClientSafeDictionary = Omit<Dictionary, "products"> & {
  products: Omit<Dictionary["products"], "resultsCount">
}

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale]
}

/**
 * Actually strips `resultsCount` (not just narrows its TypeScript type —
 * Next.js's Server->Client serialization check runs on the real runtime
 * object, so a component typed to expect `ClientSafeDictionary` still
 * fails at request time if the function is physically still there). Use
 * this whenever a dictionary needs to be passed as a prop into a "use
 * client" component from a Server Component.
 */
export function toClientSafeDictionary(dictionary: Dictionary): ClientSafeDictionary {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars -- destructured only to exclude it from productsWithoutFn below
  const { resultsCount, ...productsWithoutFn } = dictionary.products
  return { ...dictionary, products: productsWithoutFn }
}
