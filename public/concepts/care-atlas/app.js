const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];
let language =
  new URL(location.href).searchParams.get("lang") === "en" ? "en" : "ar";
let products = [],
  selectedSlug = "proxeed-plus",
  category = "all",
  query = "",
  detail = "composition";
const text = () => copy[language];
const local = (p) => (language === "en" ? { ...p, ...p.en } : p);
const node = (tag, className, content) => {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (content !== undefined) element.textContent = content;
  return element;
};
const matches = () =>
  products.filter(
    (p) =>
      (category === "all" || p.categorySlug === category) &&
      `${p.name} ${p.nameArabic || ""}`.toLocaleLowerCase().includes(query),
  );
const selected = () => products.find((p) => p.slug === selectedSlug);
const mailto = (p) =>
  `mailto:info@nilepharmafood.com?subject=${encodeURIComponent(`Product inquiry: ${p.name}`)}`;

function setLanguage(next, updateURL = true) {
  language = next;
  document.documentElement.lang = next;
  document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  document.title =
    next === "ar"
      ? "أطلس العناية — نايل فارما فود / نموذج 03"
      : "The Care Atlas — Nile Pharma Food / Study 03";
  $$("[data-i18n]").forEach((element) => {
    element.textContent = text()[element.dataset.i18n] || "";
  });
  $("#language").textContent = next === "ar" ? "EN" : "عربي";
  $("#language").setAttribute(
    "aria-label",
    next === "ar" ? "EN — Switch to English" : "عربي — التبديل إلى العربية",
  );
  $("#search").placeholder = text().search;
  $("#search").setAttribute("aria-label", text().search);
  $(".filters").setAttribute("aria-label", text().filterLabel);
  $(".product-tabs").setAttribute("aria-label", text().detailLabel);
  $(".product-stage").setAttribute("aria-label", text().stageLabel);
  $("#menu-button").setAttribute("aria-label", text().openMenu);
  $("#close-menu").setAttribute("aria-label", text().closeMenu);
  $("#contact-email").setAttribute(
    "aria-label",
    `${text().contactAction} — ${text().emailLabel}`,
  );
  $("#product-list").setAttribute("aria-label", text().listLabel);
  if (updateURL) {
    const url = new URL(location.href);
    url.searchParams.set("lang", next);
    history.replaceState(null, "", url);
  }
  renderList();
  renderProduct();
}
function renderList() {
  const list = $("#product-list"),
    rows = matches();
  list.replaceChildren();
  $("#empty").hidden = rows.length > 0 || products.length === 0;
  $(".product-stage").hidden = rows.length === 0;
  $("#catalog-count").textContent =
    `${String(rows.length).padStart(2, "0")} ${text().productCount}`;
  if (rows.length && !rows.some((p) => p.slug === selectedSlug)) {
    selectedSlug = rows[0].slug;
    detail = "composition";
  }
  for (const product of rows) {
    const active = product.slug === selectedSlug;
    const button = node("button", `product-row${active ? " active" : ""}`);
    button.type = "button";
    button.dataset.slug = product.slug;
    button.setAttribute("aria-pressed", String(active));
    button.setAttribute("aria-controls", "product-file");
    const ordinal = String(products.indexOf(product) + 1).padStart(2, "0");
    const number = node("span", "mono", ordinal);
    number.setAttribute("aria-hidden", "true");
    const label = node("span", "row-label");
    label.append(
      node("strong", "", product.name),
      node(
        "small",
        "",
        language === "ar"
          ? product.nameArabic || "CA-MI / أجهزة طبية"
          : product.categorySlug === "medical-devices"
            ? "CA-MI / MEDICAL DEVICE"
            : "ALFASIGMA / SUPPLEMENT",
      ),
    );
    const arrow = node("span", "row-arrow", "↙");
    arrow.setAttribute("aria-hidden", "true");
    button.append(number, label, arrow);
    button.addEventListener("click", () => selectProduct(product.slug));
    button.addEventListener("keydown", (event) => {
      if (
        ![
          "ArrowDown",
          "ArrowUp",
          "ArrowLeft",
          "ArrowRight",
          "Home",
          "End",
        ].includes(event.key)
      )
        return;
      event.preventDefault();
      const buttons = [...list.querySelectorAll("button")];
      let i = buttons.indexOf(button);
      if (event.key === "Home") i = 0;
      else if (event.key === "End") i = buttons.length - 1;
      else
        i =
          (i +
            (["ArrowDown", "ArrowRight"].includes(event.key) ? 1 : -1) +
            buttons.length) %
          buttons.length;
      selectProduct(buttons[i].dataset.slug);
      const target = list.querySelector(
        `[data-slug="${buttons[i].dataset.slug}"]`,
      );
      target.focus({ preventScroll: true });
      target.scrollIntoView({
        block: "nearest",
        inline: "nearest",
        behavior: "instant",
      });
    });
    list.append(button);
  }
}
function selectProduct(slug) {
  selectedSlug = slug;
  detail = "composition";
  // Keep the focused button in the DOM; don't reset keyboard users to body.
  $$(".product-row").forEach((button) => {
    const active = button.dataset.slug === slug;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  renderProduct();
  $("#product-announcement").textContent =
    `${text().selected} ${selected().name}`;
}
function renderProduct() {
  const product = selected();
  if (!product) return;
  const p = local(product);
  const image = $("#product-image");
  if (image.getAttribute("src") !== p.image) image.src = p.image;
  image.alt = p.name;
  $("#product-title").textContent = p.name;
  $("#product-subtitle").textContent = p.availableForm || "";
  $("#product-description").textContent = p.shortDescription || "";
  $("#stage-category").textContent =
    p.categorySlug === "medical-devices"
      ? "CA-MI / MEDICAL DEVICE"
      : "ALFASIGMA / FOOD SUPPLEMENT";
  $("#stage-number").textContent =
    `${String(products.indexOf(product) + 1).padStart(2, "0")} — ${String(products.length).padStart(2, "0")}`;
  $('[data-detail="composition"]').textContent =
    p.categorySlug === "medical-devices"
      ? text().specifications
      : text().composition;
  $(".product-stage").setAttribute("aria-busy", "false");
  $("#contact-email").href = mailto(p);
  $$(".detail-tab").forEach((button) => {
    const active = button.dataset.detail === detail;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  const area = $("#product-detail");
  area.replaceChildren();
  if (detail === "composition") {
    if (p.composition?.length) {
      const table = node("table", "composition-table");
      table.setAttribute(
        "aria-label",
        p.categorySlug === "medical-devices"
          ? text().specifications
          : text().composition,
      );
      const body = node("tbody");
      for (const item of p.composition) {
        const row = node("tr"),
          label = node("th", "", item.label);
        label.scope = "row";
        row.append(label, node("td", "", item.value));
        body.append(row);
      }
      table.append(body);
      area.append(table);
      if (p.compositionNote)
        area.append(node("p", "composition-note", p.compositionNote));
    } else area.append(node("p", "no-data", text().noComposition));
  } else if (detail === "usage") {
    area.append(node("p", "usage-copy", p.usage || text().noInfo));
  } else if (p.downloadUrl) {
    const link = node("a", "pdf-link");
    link.href = p.downloadUrl;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    const label = node("span", "", `${text().openLeaflet} / ${p.name}`);
    label.append(node("small", "", text().newWindow));
    const icon = node("span", "", "↗");
    icon.setAttribute("aria-hidden", "true");
    link.append(label, icon);
    area.append(link);
  } else {
    area.append(node("p", "no-data", text().noLeaflet));
    const ask = node("a", "line-link", text().askProduct + " ↗");
    ask.href = mailto(p);
    area.append(ask);
  }
  // The reading chapter links to the selected product only when a real PDF
  // exists. Otherwise retain its clearly named Proxeed Plus source, never a
  // fabricated leaflet or a marketing-file substitute.
  const source = p.downloadUrl
    ? p
    : products.find((item) => item.slug === "proxeed-plus");
  if (source?.downloadUrl) {
    $("#reading-leaflet").href = source.downloadUrl;
    $("#reading-leaflet-name").textContent = source.name;
  }
}
$(".product-stage").id = "product-file";
$("#product-detail").setAttribute("aria-live", "polite");
$("#product-list").setAttribute("role", "group");
$("#language").addEventListener("click", () =>
  setLanguage(language === "ar" ? "en" : "ar"),
);
$$(".filter").forEach((button) =>
  button.addEventListener("click", () => {
    category = button.dataset.category;
    $$(".filter").forEach((filter) => {
      filter.classList.toggle("active", filter === button);
      filter.setAttribute("aria-pressed", String(filter === button));
    });
    renderList();
    renderProduct();
  }),
);
$("#search").addEventListener("input", (event) => {
  query = event.target.value.trim().toLocaleLowerCase();
  renderList();
  renderProduct();
});
$$(".detail-tab").forEach((button) =>
  button.addEventListener("click", () => {
    detail = button.dataset.detail;
    renderProduct();
  }),
);
const menu = $("#mobile-menu"),
  opener = $("#menu-button");
opener.addEventListener("click", () => {
  menu.showModal();
  opener.setAttribute("aria-expanded", "true");
  document.body.classList.add("menu-open");
});
$("#close-menu").addEventListener("click", () => menu.close());
menu.addEventListener("close", () => {
  opener.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
  opener.focus({ preventScroll: true });
});
menu.querySelectorAll('a[href^="#"]').forEach((link) =>
  link.addEventListener("click", (event) => {
    event.preventDefault();
    const destination = $(link.getAttribute("href"));
    menu.close();
    destination.scrollIntoView({
      behavior: matchMedia("(prefers-reduced-motion: reduce)").matches
        ? "instant"
        : "smooth",
    });
    destination.setAttribute("tabindex", "-1");
    destination.focus({ preventScroll: true });
  }),
);
$("#year").textContent = new Date().getFullYear();
setLanguage(language, false);
try {
  const response = await fetch("./catalog.json");
  if (!response.ok) throw new Error(`Catalog HTTP ${response.status}`);
  products = await response.json();
  renderList();
  renderProduct();
} catch {
  $("#product-list").replaceChildren(node("p", "load-note", text().error));
  $(".product-stage").hidden = true;
  $(".product-stage").setAttribute("aria-busy", "false");
}
